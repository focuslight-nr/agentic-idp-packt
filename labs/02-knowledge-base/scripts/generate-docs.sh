#!/usr/bin/env bash
# Regenerates kb/generated/ from the platform's own sources.
# Output must be deterministic (sorted, no timestamps) so the CI freshness check can diff it.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
OUT="$ROOT/labs/02-knowledge-base/kb/generated"
mkdir -p "$OUT"
cd "$ROOT"

header() {
  echo "<!-- Generated by labs/02-knowledge-base/scripts/generate-docs.sh. Do not edit by hand. -->"
  echo
  echo "# $1"
  echo
}

{
  header "Golden path chart reference"
  helm-docs --chart-search-root labs/01-golden-path/platform/charts --dry-run 2>/dev/null
} > "$OUT/service-chart.md"

{
  header "Service catalog"
  echo "| App | Namespace | Owner | Image | Source |"
  echo "|---|---|---|---|---|"
  for app_file in $(ls labs/*/apps/*/app.yaml | sort); do
    dir="$(dirname "$app_file")"
    image="$(yq '.image.repository + ":" + .image.tag' "$dir/values.yaml")"
    yq -r "\"| \" + .name + \" | \" + .namespace + \" | \" + .owner + \" | \`$image\` | \`$dir\` |\"" "$app_file"
  done
} > "$OUT/service-catalog.md"

{
  header "Alerts and runbooks"
  echo "| Alert | Severity | Summary | Runbook |"
  echo "|---|---|---|---|"
  for rules in $(ls labs/*/alerts/*.yaml 2>/dev/null | sort); do
    yq -r '.spec.groups[].rules[] | select(.alert) |
      "| " + .alert + " | " + .labels.severity + " | " + .annotations.summary + " | " + (.annotations.runbook_url | sub(".*/labs/"; "labs/")) + " |"' "$rules"
  done
} > "$OUT/alerts.md"

{
  header "Policies"
  echo "| Policy | Title | Description | Source |"
  echo "|---|---|---|---|"
  for policy in $(ls labs/*/policies/*.yaml 2>/dev/null | sort); do
    yq -r "select(.kind == \"ClusterPolicy\") |
      \"| \" + .metadata.name + \" | \" + .metadata.annotations.\"policies.kyverno.io/title\" + \" | \" + .metadata.annotations.\"policies.kyverno.io/description\" + \" | \`$policy\` |\"" "$policy"
  done
} > "$OUT/policies.md"

{
  header "Agent identities and permissions"
  echo "| Identity | Role | Resources | Verbs | Source |"
  echo "|---|---|---|---|---|"
  for rbac in $(ls labs/*/platform/rbac*.yaml labs/*/rbac/*.yaml 2>/dev/null | sort); do
    yq -r "select(.kind == \"ClusterRole\" or .kind == \"Role\") | .metadata.name as \$role | (.metadata.annotations.\"platform.workshop/identity\" // \"-\") as \$id |
      .rules[] | \"| \" + \$id + \" | \" + \$role + \" | \" + (.resources | join(\", \")) + \" | \" + (.verbs | join(\", \")) + \" | \`$rbac\` |\"" "$rbac"
  done
} > "$OUT/agent-identities.md"

echo "Knowledge base regenerated in ${OUT#"$ROOT"/}"
